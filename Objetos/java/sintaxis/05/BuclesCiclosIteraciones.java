public class BuclesCiclosIteraciones {
    public static void main(String[] args) {
        // for: índice y condición
        for (int i = 0; i < 10; i++) {
            // ...
        }

        // post-incremento
        int i = 10;
        int a = i++; // a → 10; i → 11;
        int b = ++i; // b → 12; i → 12;

        // while
        int condicion = 15;
        while (condicion < 18) {
            condicion++;
        }

        // do-while
        condicion = 15;
        do {
            // ...
        } while (condicion < 18);

        // --------------------------------------------------------------------


    }
}
