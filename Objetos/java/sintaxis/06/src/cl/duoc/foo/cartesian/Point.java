package cl.duoc.foo.cartesian;

public class Point {
    private int x;
    private int y;

    public void setX(int number) {
        this.x = number;
    }

    public int getX() {
        return x;
    }

    public void setY(int number) {
        this.y = number;
    }

    public int getY() {
        return y;
    }
}
